# -- resolution (workspace -> projects -> repositories) -----------------------


def test_resolution_order_reaches_repository_through_project(tmp_path: Path) -> None:
    root = tmp_path / "WS"
    write(root / "Workspace.yaml", VALID_WORKSPACE)
    write(
        root / "Projects" / "Alpha" / "project.yaml",
        {**VALID_PROJECT, "repository": {"adapter": "local_git", "path": "repos/alpha"}},
    )

    workspace = resolve_workspace(root)

    assert [p.ref.name for p in workspace.projects] == ["Alpha"]
    resolved = workspace.projects[0]
    assert resolved.repository is not None
    assert resolved.repository.adapter == "local_git"
    assert resolved.repository.path == "repos/alpha"


def test_resolve_missing_workspace_manifest(tmp_path: Path) -> None:
    with pytest.raises(NotFoundError, match="No workspace manifest"):
        resolve_workspace(tmp_path / "nope")


def test_resolve_registered_project_without_manifest_fails_closed(tmp_path: Path) -> None:
    root = tmp_path / "WS"
    write(root / "Workspace.yaml", VALID_WORKSPACE)
    # Alpha is registered but its project.yaml is absent.

    with pytest.raises(ValidationError, match="is missing"):
        resolve_workspace(root)


def test_workspace_with_no_projects_resolves_empty(tmp_path: Path) -> None:
    root = tmp_path / "WS"
    write(root / "Workspace.yaml", {"schema_version": 1, "workspace": {"name": "Empty"}})

    workspace = resolve_workspace(root)

    assert workspace.projects == ()


